export function scriptJson(value) {
  return JSON.stringify(value)
    .replaceAll("<", "\\u003c")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
}

export function generatedLauncherSource(
  gameId,
  runtimeHash,
  requiresJspi,
  extraArgs = [],
  compatibility = "none",
  flashAssetRoot = null,
) {
  return `// Generated by krkrtools. Keep game assets out of the initial Wasm bundle.
const status = (message) => {
  let element = document.getElementById("krkrtools-status");
  if (!element) {
    element = document.createElement("pre");
    element.id = "krkrtools-status";
    document.body.prepend(element);
  }
  element.textContent = message;
};
let failed = false;
const showFailure = (error) => {
  if (failed) return;
  failed = true;
  const message = error instanceof Error ? error.stack || error.message : String(error || "The game runtime stopped.");
  const loading = document.getElementById("loading");
  if (loading) loading.style.display = "none";
  if (typeof globalThis.Module?.showError === "function") globalThis.Module.showError(message);
  else status(message);
};
try {
  // Native/Asyncify failures may reject after startup has returned. Make the
  // failure visible instead of leaving the last fetched-file count spinning.
  const module = globalThis.Module ??= {};
  const previousAbort = module.onAbort;
  module.onAbort = (reason) => {
    showFailure(reason);
    if (typeof previousAbort === "function") previousAbort.call(module, reason);
  };
  globalThis.addEventListener("unhandledrejection", event => showFailure(event.reason));
  globalThis.addEventListener("error", event => {
    if (event.error || event.message) showFailure(event.error || event.message);
  });
  if (!globalThis.crossOriginIsolated || typeof SharedArrayBuffer === "undefined") {
    throw new Error("This runtime needs cross-origin isolation. Use krkrtools serve, or configure COOP/COEP on your HTTPS host.");
  }
  if (typeof WebAssembly !== "object") throw new Error("WebAssembly is unavailable.");
  if (${requiresJspi} && (typeof WebAssembly.Suspending !== "function" || typeof WebAssembly.promising !== "function")) {
    throw new Error("This supplied runtime needs WebAssembly JSPI, which is unavailable in this browser.");
  }
  if (!navigator.storage?.getDirectory) throw new Error("This runtime needs OPFS storage support.");
  // The upstream runtime has cache migration/clear operations. Scope every OPFS
  // request BEFORE loading its code so those operations cannot reach other data.
  const storage = navigator.storage;
  const original = storage.getDirectory.bind(storage);
  const cacheRoot = await (await original()).getDirectoryHandle(${scriptJson(`krkrtools-${gameId}`)}, { create: true });
  Object.defineProperty(storage, "getDirectory", {
    configurable: true, value: async () => cacheRoot
  });
  if (await storage.getDirectory() !== cacheRoot) throw new Error("Could not isolate the game's asset cache.");
  // Desktop framebuffers do not carry browser-compositing alpha. In particular,
  // SDL can draw valid RGB with alpha=0, making a normal WebGL canvas invisible.
  const canvas = document.getElementById?.("canvas");
  if (canvas?.getContext) {
    const getContext = canvas.getContext.bind(canvas);
    canvas.getContext = (type, options, ...rest) => getContext(type,
      /^(?:webgl2?|experimental-webgl)$/.test(type) ? { ...options, alpha: false } : options, ...rest);
  }
  const extraArgs = ${scriptJson(extraArgs)};
  if (extraArgs.length) {
    const module = globalThis.Module ??= {};
    const callbacks = module.preRun;
    module.preRun = [...(Array.isArray(callbacks) ? callbacks : callbacks ? [callbacks] : []), () => {
      // Upstream inserts defaults first; its option parser gives earlier values
      // priority. Mutate the same argv array captured by Emscripten.
      module.arguments?.unshift(...extraArgs);
    }];
  }
  ${
    compatibility === "kag3"
      ? `const { installKagControls } = await import("./kag3.mjs");
  installKagControls({ gameId: ${scriptJson(gameId)} });`
      : ""
  }
  ${
    flashAssetRoot
      ? `const { installFlash } = await import("./flash.mjs");
  installFlash({ gameId: ${scriptJson(gameId)}, assetBase: new URL(${scriptJson(`../${flashAssetRoot}`)}, import.meta.url).href,
    ruffleBase: new URL("./ruffle/", import.meta.url).href });`
      : ""
  }
  const engine = document.createElement("script");
  engine.src = new URL(${scriptJson(`../krkrz.js?v=${runtimeHash}`)}, import.meta.url).href;
  engine.async = true;
  engine.onerror = () => showFailure("Could not load the KiriKiri Z runtime.");
  document.body.append(engine);
} catch (error) {
  showFailure(error);
  console.error(error);
}
`;
}
